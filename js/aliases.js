// Category parser + global nickname aliases.
// Data format (see js/data/*.js):
//   @Category name ~ optional hint     [group: tag]
//   1: Answer, Answer/Alias, ...       (1 = Entrance Ramp ... 6 = In the Stands)
window.CATS = [];
window.addCats = function (txt) {
  let cur = null;
  txt.split('\n').forEach((line) => {
    line = line.trim();
    if (!line || line.startsWith('//')) return;
    if (line[0] === '@') {
      let body = line.slice(1);
      let group = null;
      const gm = body.match(/\[group:\s*([^\]]+)\]/);
      if (gm) { group = gm[1].trim(); body = body.replace(gm[0], ''); }
      const [name, hint] = body.split('~').map((s) => s.trim());
      cur = { name, hint: hint || '', group, answers: [] };
      window.CATS.push(cur);
      return;
    }
    const m = line.match(/^([1-6])\s*:\s*(.*)$/);
    if (!m || !cur) return;
    const tier = +m[1];
    m[2].split(',').forEach((a) => {
      a = a.trim();
      if (!a) return;
      const names = a.split('/').map((s) => s.trim()).filter(Boolean);
      if (cur.answers.some((x) => x.names[0].toLowerCase() === names[0].toLowerCase())) return;
      cur.answers.push({ tier, display: names[0], names });
    });
  });
};

